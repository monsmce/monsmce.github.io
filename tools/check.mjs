#!/usr/bin/env node
// Pre-launch check. Run from the project folder:  node tools/check.mjs
// Rewrites MEDIA.md and lists every empty media slot and empty text.
// Add --strict to exit with an error when anything is empty.
import { existsSync, writeFileSync } from 'node:fs';
import * as c from '../js/content.js';

const slots = c.mediaSlots().map((s) => ({ ...s, filled: existsSync(s.path) }));
const empty = slots.filter((s) => !s.filled);

const todos = [];
const need = (ok, what) => { if (!ok) todos.push(what); };
need(c.site.links.email, 'site.links.email (Email key and Hire me key)');
need(c.site.links.phone, 'site.links.phone (Phone key)');
c.projects.forEach((p) => { need(p.links.repo, `projects › ${p.title} › links.repo`); need(p.links.demo, `projects › ${p.title} › links.demo (optional)`); });
c.proof.quotes.forEach((q, i) => need(q.text && q.by, `proof.quotes[${i}] (text and by)`));
c.about.lists.forEach((l) => need(l.items.length, `about.lists › ${l.title}`));
c.volunteering.forEach((v) => v.photos.forEach((ph) => { if (existsSync(ph.src)) { need(ph.alt, `alt text for ${ph.src}`); need(ph.caption, `caption for ${ph.src}`); } }));
c.about.photos.forEach((ph) => { if (existsSync(ph.src)) need(ph.alt, `alt text for ${ph.src}`); });
c.proof.badges.forEach((b) => { if (b.image && existsSync(b.image)) need(b.alt, `alt text for ${b.image}`); });

const md = [
  '# Media checklist',
  '',
  'Generated by `node tools/check.mjs`. Do not edit by hand: add the file at the path, then run the command again.',
  '',
  `**${slots.length - empty.length} of ${slots.length} filled.**`,
  '',
  '| Status | Path | Ratio / size | Type | What |',
  '|---|---|---|---|---|',
  ...slots.map((s) => `| ${s.filled ? 'filled' : 'EMPTY'} | \`${s.path}\` | ${s.ratio} | ${s.type} | ${s.what} |`),
  '',
  '## Text still to write (in js/content.js)',
  '',
  ...(todos.length ? todos.map((t) => `- [ ] ${t}`) : ['Nothing. All text is filled.']),
  '',
  'Rules: photos .jpg, max 2000 px, about 300 KB each. No identifiable children or other people without permission. Remove personal data from certificates.',
  '',
].join('\n');
writeFileSync('MEDIA.md', md);

console.log(`Media: ${slots.length - empty.length}/${slots.length} filled. Text TODOs: ${todos.length}. Details in MEDIA.md`);
for (const s of empty) console.log('  EMPTY  ' + s.path);
for (const t of todos) console.log('  TODO   ' + t);
if (process.argv.includes('--strict') && (empty.length || todos.length)) process.exit(1);
